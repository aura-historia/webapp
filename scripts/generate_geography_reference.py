#!/usr/bin/env python3
"""Generate the TypeScript ISO code tables offline from the vendored iso-codes release.

The tables mirror the backend's geographic reference (backend `src/geo/scripts/generate_reference.py`):
current ISO 3166-1 alpha-2 countries and complete ISO 3166-2 subdivision codes of one immutable
release. Country names come from the runtime locale data (`Intl.DisplayNames`). Subdivision names,
which `Intl` does not provide, are generated per app language from the release's names and its
translations (`iso_3166-2/<language>.po`); an untranslated or fuzzy entry keeps the release name.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RELEASE = "iso-codes-4.20.1"
SOURCE = ROOT / "reference" / RELEASE
OUTPUT = ROOT / "src/data/internal/geography/reference/isoCodes.gen.ts"
NAMES_OUTPUT_DIR = ROOT / "src/data/internal/geography/reference"
HASHES = {
    "1": "f01b812b57fba9f31ff621bf33e7c7570a01964dbeb5be2167e94decf538c89f",
    "2": "78c90ef7fc25b5c2631aac5f089bc9ff6ec22c025c05b6ddbc087a1f1be2e46a",
}
# The app's languages other than English, whose subdivision names come from the release's
# translations. English uses the release names themselves.
TRANSLATION_HASHES = {
    "de": "8483b0242d080b966ae30a2acb4a983428527ca10891518bb17ff6f16152a5e7",
    "es": "40fdef4fdb4c6d73326aefb96bc9c4c1ccc77f865d1a605a88725bb13eb6aa0a",
    "fr": "6b73f111c47cfa7d4e3b0f8f355179bf8339f4938949b6f22faa44cc929be599",
    "it": "0c40fba5b6eae51b79dcf3d3411bf1f75c9e0335a74b370f84222fdeca00f62a",
}
NAME_LANGUAGES = ("en", *TRANSLATION_HASHES)
LICENSE_HEADER = [
    "// SPDX-FileCopyrightText: 2016 Dr. Tobias Quathamer <toddy@debian.org> and the iso-codes translators",
    "// SPDX-License-Identifier: LGPL-2.1-or-later",
]


def load_records(source: Path = SOURCE) -> dict:
    records = {}
    for part, digest in HASHES.items():
        raw = (source / f"iso_3166-{part}.json").read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f"Reference part {part} changed; add a new release instead")
        records[part] = json.loads(raw)[f"3166-{part}"]
    return records


def render(records: dict) -> str:
    countries = sorted(row["alpha_2"] for row in records["1"])
    subdivisions = sorted(row["code"] for row in records["2"])
    if len(countries) != 249 or len(countries) != len(set(countries)):
        raise ValueError("Country release is incomplete or contains duplicate codes")
    if len(subdivisions) != len(set(subdivisions)):
        raise ValueError("Subdivision release contains duplicate codes")
    if not all(re.fullmatch(r"[A-Z]{2}-[A-Z0-9]{1,3}", code) for code in subdivisions):
        raise ValueError("Subdivision release contains malformed codes")
    if not all(code[:2] in countries for code in subdivisions):
        raise ValueError("Subdivision release contains an unrecognized country")

    by_country: dict[str, list[str]] = {}
    for code in subdivisions:
        by_country.setdefault(code[:2], []).append(code[3:])

    lines = [
        f"// Generated by scripts/generate_geography_reference.py from reference/{RELEASE}; do not edit.",
        "// SPDX-FileCopyrightText: 2016 Dr. Tobias Quathamer <toddy@debian.org>",
        "// SPDX-License-Identifier: LGPL-2.1-or-later",
        "",
        f'export const ISO_CODES_RELEASE = "{RELEASE}";',
        "",
        "/** Current ISO 3166-1 alpha-2 country codes, sorted. */",
        "export const ISO_COUNTRY_CODES: readonly string[] = [",
    ]
    lines.extend(f'    "{code}",' for code in countries)
    lines.append("];")
    lines.append("")
    lines.append("/** ISO 3166-2 subdivision suffixes by country, space separated and sorted. */")
    lines.append("export const ISO_SUBDIVISION_SUFFIXES: Readonly<Record<string, string>> = {")
    lines.extend(f'    {country}: "{" ".join(codes)}",' for country, codes in by_country.items())
    lines.append("};")
    return "\n".join(lines) + "\n"


def _unquote(line: str) -> str:
    return json.loads(line)


def parse_po(text: str) -> dict[str, tuple[str, str]]:
    """Maps each subdivision code to `(msgid, msgstr)`; fuzzy and empty entries are left out."""
    entries: dict[str, tuple[str, str]] = {}
    for block in re.split(r"\n\s*\n", text):
        lines = block.strip().splitlines()
        codes = [code for line in lines if line.startswith("#.") for code in re.findall(r"\b[A-Z]{2}-[A-Z0-9]{1,3}\b", line)]
        if not codes or any(line.startswith("#,") and "fuzzy" in line for line in lines):
            continue
        fields: dict[str, str] = {}
        current = None
        for line in lines:
            if line.startswith("#"):
                continue
            match = re.match(r'(msgid|msgstr) (".*")$', line)
            if match:
                current = match.group(1)
                fields[current] = _unquote(match.group(2))
            elif current and line.startswith('"'):
                fields[current] += _unquote(line)
        if fields.get("msgid") and fields.get("msgstr"):
            for code in codes:
                entries[code] = (fields["msgid"], fields["msgstr"])
    return entries


def load_translations(source: Path = SOURCE) -> dict[str, dict[str, tuple[str, str]]]:
    translations = {}
    for language, digest in TRANSLATION_HASHES.items():
        raw = (source / "iso_3166-2" / f"{language}.po").read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f"Translation {language} changed; add a new release instead")
        translations[language] = parse_po(raw.decode("utf-8"))
    return translations


def render_names(records: dict, translations: dict, language: str) -> str:
    names = {row["code"]: row["name"] for row in records["2"]}
    entries = translations.get(language, {})
    lines = [
        f"// Generated by scripts/generate_geography_reference.py from reference/{RELEASE}; do not edit.",
        *LICENSE_HEADER,
        "",
        f"/** ISO 3166-2 subdivision names for `{language}`, by complete code. */",
        "const SUBDIVISION_NAMES: Readonly<Record<string, string>> = {",
    ]
    for code in sorted(names):
        name = names[code]
        entry = entries.get(code)
        # A translation of an outdated release name would name a different subdivision.
        if entry and entry[0] == name:
            name = entry[1]
        lines.append(f"    {json.dumps(code)}: {json.dumps(name, ensure_ascii=False)},")
    lines.append("};")
    lines.append("")
    lines.append("export default SUBDIVISION_NAMES;")
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, bytes]:
    records = load_records()
    translations = load_translations()
    files = {OUTPUT: render(records).encode("utf-8")}
    for language in NAME_LANGUAGES:
        path = NAMES_OUTPUT_DIR / f"subdivisionNames.{language}.gen.ts"
        files[path] = render_names(records, translations, language).encode("utf-8")
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify tables without writing files")
    check = parser.parse_args().check
    for path, generated in outputs().items():
        if check:
            if not path.is_file() or path.read_bytes() != generated:
                raise SystemExit("Geography reference tables are stale; run scripts/generate_geography_reference.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(generated)


if __name__ == "__main__":
    main()
