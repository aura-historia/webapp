#!/usr/bin/env python3
"""Generate the TypeScript ISO code tables offline from the vendored iso-codes release.

The tables mirror the backend's geographic reference (backend `src/geo/scripts/generate_reference.py`):
current ISO 3166-1 alpha-2 countries and complete ISO 3166-2 subdivision codes of one immutable
release. Names are not generated; display names come from the runtime locale data.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RELEASE = "iso-codes-4.20.1"
SOURCE = ROOT / "reference" / RELEASE
OUTPUT = ROOT / "src/data/internal/geography/reference/isoCodes.gen.ts"
HASHES = {
    "1": "f01b812b57fba9f31ff621bf33e7c7570a01964dbeb5be2167e94decf538c89f",
    "2": "78c90ef7fc25b5c2631aac5f089bc9ff6ec22c025c05b6ddbc087a1f1be2e46a",
}


def load_records(source: Path = SOURCE) -> dict:
    records = {}
    for part, digest in HASHES.items():
        raw = (source / f"iso_3166-{part}.json").read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f"Reference part {part} changed; add a new release instead")
        records[part] = json.loads(raw)[f"3166-{part}"]
    return records


def render(records: dict) -> str:
    countries = sorted(row["alpha_2"] for row in records["1"])
    subdivisions = sorted(row["code"] for row in records["2"])
    if len(countries) != 249 or len(countries) != len(set(countries)):
        raise ValueError("Country release is incomplete or contains duplicate codes")
    if len(subdivisions) != len(set(subdivisions)):
        raise ValueError("Subdivision release contains duplicate codes")
    if not all(re.fullmatch(r"[A-Z]{2}-[A-Z0-9]{1,3}", code) for code in subdivisions):
        raise ValueError("Subdivision release contains malformed codes")
    if not all(code[:2] in countries for code in subdivisions):
        raise ValueError("Subdivision release contains an unrecognized country")

    by_country: dict[str, list[str]] = {}
    for code in subdivisions:
        by_country.setdefault(code[:2], []).append(code[3:])

    lines = [
        f"// Generated by scripts/generate_geography_reference.py from reference/{RELEASE}; do not edit.",
        "// SPDX-FileCopyrightText: 2016 Dr. Tobias Quathamer <toddy@debian.org>",
        "// SPDX-License-Identifier: LGPL-2.1-or-later",
        "",
        f'export const ISO_CODES_RELEASE = "{RELEASE}";',
        "",
        "/** Current ISO 3166-1 alpha-2 country codes, sorted. */",
        "export const ISO_COUNTRY_CODES: readonly string[] = [",
    ]
    lines.extend(f'    "{code}",' for code in countries)
    lines.append("];")
    lines.append("")
    lines.append("/** ISO 3166-2 subdivision suffixes by country, space separated and sorted. */")
    lines.append("export const ISO_SUBDIVISION_SUFFIXES: Readonly<Record<string, string>> = {")
    lines.extend(f'    {country}: "{" ".join(codes)}",' for country, codes in by_country.items())
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify tables without writing files")
    generated = render(load_records()).encode("utf-8")
    if parser.parse_args().check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("Geography reference tables are stale; run scripts/generate_geography_reference.py")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(generated)


if __name__ == "__main__":
    main()
